_MJS_KEY_RE = re.compile(r'^\s*"([^"]+/[^"]+)":\s*\{', re.M)


def _read_mirror_keys() -> set[str]:
    """Keys of control/cloud.mjs CLOUD_MODELS, bounded by the object's closing
    `};` so nothing else in the file can match."""
    text = (REPO / "control" / "cloud.mjs").read_text(encoding="utf-8")
    start = text.index("export const CLOUD_MODELS = {")
    end = text.index("\n};", start)
    return set(_MJS_KEY_RE.findall(text[start:end]))


def check_roster_drift(c: Check, bench_config) -> None:
    """NON-BLOCKING in both modes: config.py CLOUD_ORCAROUTER_PROVIDER['models']
    is CANONICAL; control/cloud.mjs CLOUD_MODELS is a deliberate mirror the
    control plane serves. The mirror is known to lag — drift is a surfaced
    defect, not a gate on launching."""
    if bench_config is None:
        c.add("roster drift", False, "skipped — harness import failed", blocking=False)
        return
    config_keys = set(bench_config.CLOUD_ORCAROUTER_PROVIDER.get("models", {}))
    try:
        mirror_keys = _read_mirror_keys()
    except Exception as exc:  # noqa: BLE001
        c.add(
            "roster drift",
            False,
            f"could not parse control/cloud.mjs CLOUD_MODELS: {exc}",
            blocking=False,
        )
        return
    if config_keys == mirror_keys:
        c.add(
            "roster drift",
            True,
            f"config.py and control/cloud.mjs agree ({len(config_keys)} keys)",
        )
        return
    parts = [
        f"config.py has {len(config_keys)} keys, control/cloud.mjs mirrors {len(mirror_keys)}"
    ]
    for label, diff in (
        ("missing in mirror", config_keys - mirror_keys),
        ("missing in config", mirror_keys - config_keys),
    ):
        if not diff:
            continue
        shown = sorted(diff)
        extra = f" +{len(shown) - 6} more" if len(shown) > 6 else ""
        parts.append(f"{label}: {', '.join(shown[:6])}{extra}")
    parts.append("config.py is canonical; mirror lag is a surfaced defect, not a gate")
    c.add("roster drift", False, " — ".join(parts), blocking=False)


def check_feedback_completeness(c: Check) -> None:
    """BLOCKING: every graded gate must have a human-written feedback override.

    WO-FEEDBACK-VOICE-3 (2026-08-30): the feedback voice is SINGLE-SYSTEM. There
    is NO title-derived fallback — `_humanize_check` raises
    `MissingFeedbackOverrideError` for a gate with no entry in
    `grader/feedback.json`, because the title-derived sentence
    (a test title) states the RULE and answers the gate's question for free.

    A missing override is therefore a misconfigured benchmark, not a graceful
    degradation. This check refuses to let a run start until every gate is
    covered. It is the launch half of the guarantee; the CI half is
    `test_every_gate_token_has_an_override`.
    """
    try:
        sys.path.insert(0, str(REPO))
        from harness.adapters.backgammon import missing_feedback_overrides
    except Exception as exc:  # noqa: BLE001
        c.add("feedback completeness", False, f"could not import harness: {exc}")
        return

    gates_dir = REPO / "grader"
    try:
        missing = sorted(missing_feedback_overrides(gates_dir))
    except Exception as exc:  # noqa: BLE001
        c.add(
            "feedback completeness",
            False,
            f"could not enumerate feedback overrides: {exc}",
        )
        return

    if not missing:
        c.add(
            "feedback completeness",
            True,
            "every graded gate has a human-written feedback override",
        )
        return

    shown = ", ".join(missing[:10])
    extra = f" (+{len(missing) - 10} more)" if len(missing) > 10 else ""
    c.add(
        "feedback completeness",
        False,
        f"NO-GO: {len(missing)} gate(s) lack a feedback override: "
        f"{shown}{extra}. Write a symptom sentence for each in "
        "grader/feedback.json before launching.",
    )


def check_run_dir(c: Check, args) -> None:
    """Report whether the chosen model's campaign slot is already occupied.

    READ-ONLY — never writes or deletes under runs/. Archive, never delete
    (RUNBOOK §0 3a); under the tree layout a reset MINTS a new tree rather
    than unlinking (control/tree.mjs).

    Slot resolution mirrors control/campaign.mjs `campaignTargetFor`: the
    active tree WINS when the pointer exists — cloud campaigns land at
    runs/<tree>/cloud/<router>/<provider>/<model>, local ones at
    runs/<tree>/local/local-llm-proxy/omlx/<model>; only a bench with NO
    pointer uses the legacy flat runs/cumulative-<model> slot.
    """
    runs_root = REPO / "runs"
    tree_id, tree_err = _read_tree_pointer(runs_root)
    if tree_err:
        c.add(
            "campaign slot",
            False,
            f"{tree_err} — refusing to guess which tree is live (control/tree.mjs)",
        )
        return
    if args.cloud:
        provider = str(args.provider or "").strip()
        model = str(args.model or "").strip()
        router = str(args.router or "orcarouter").strip()
        if tree_id:
            rel = (
                Path(tree_id)
                / "cloud"
                / _segment(router, "orcarouter")
                / _segment(provider, "unknown-provider")
                / _segment(model, "unknown-model")
            )
        else:
            rel = Path(_campaign_dir_name(f"{provider}/{model}"))
    else:
        alias = str(args.model or "").strip()
        if alias.startswith("local-llm-proxy/"):
            alias = alias[len("local-llm-proxy/") :]
        if tree_id:
            rel = (
                Path(tree_id)
                / "local"
                / "local-llm-proxy"
                / "omlx"
                / _segment(alias, "unknown-model")
            )
        else:
            rel = Path(_campaign_dir_name(alias))
    tree_note = (
        f"active tree {tree_id}" if tree_id else "no active tree — legacy flat layout"
    )
    slot = runs_root / rel
    if not slot.exists():
        c.add("campaign slot", True, f"{rel} ABSENT ({tree_note}) — clean slate")
        return
    stamp = "$(date +%Y%m%dT%H%M%S)"
    c.add(
        "campaign slot",
        False,
        f"{rel} EXISTS ({tree_note}) — a campaign occupies this slot. "
        "ARCHIVE IT, NEVER DELETE (legacy: mv runs/<dir> runs/<dir>.<why>-"
        f"{stamp}; tree layout: reset mints a NEW tree, never unlink). "
        "A launch into it RESUMES that campaign — intended only for resumes.",
    )


# ── the board's during-the-run surface ──────────────────────────────────────
#
# LIVENESS IS NOT WIRING (AGENTS.md §2.1). The board answering 200 on :7717
# proves nothing about whether its sources RESOLVE, exactly as a port answering
# proved nothing about identity. This asserts the SEAM instead: the reader's own
# resolver, invoked directly, against the streams actually on disk.
#
# THE DEFECT THIS EXISTS FOR (2026-08-29). LIVE-STREAM.md documents the stream
# at `runs/<run>/live.jsonl`, but the harness opens it in `run_cell` via
# `LiveStream.for_run(run_dir)` where `run_dir` is the CELL directory — so it
# lands at `<campaign>/memory<ARM>/cell-<seq>/live.jsonl`, one level below the
# campaign dir `activeRun()` resolves. Both dashboard readers joined the bare
# filename onto `run.dir` and opened a path that never exists, so the gate wall
# and the learning matrix sat empty for the entire life of every run while the
# harness appended to a file a few directories down.
#
# WHY NEITHER TEST SUITE CAUGHT IT, WHICH IS THE REAL LESSON. All 12 contract
# tests in tests/test_live_stream.py pass `tmp_path` to `for_run`; the reader's
# tests passed a synthetic directory to the reader. Each half was verified
# against a directory IT SUPPLIED, so both agreed in tests and disagreed on
# disk. A writer test and a reader test cannot find a disagreement about WHERE —
# only something that reads the writer's real output with the reader's real code
# can, and that is this check.
STREAM_SEAM_JS = """
import { activeRun, liveStreamPath } from './sources/_runtime.mjs';
import { promises as fs } from 'node:fs';
import { join } from 'node:path';

// GROUND TRUTH, gathered WITHOUT the resolver — a check that used
// liveStreamPath to find what liveStreamPath should find proves nothing.
// Skips worktree/.git: the model's checkout is large and never holds a stream.
async function walk(dir, depth, hits) {
  if (depth > 4) return hits;
  let ents = [];
  try { ents = await fs.readdir(dir, { withFileTypes: true }); } catch { return hits; }
  for (const e of ents) {
    if (e.isFile() && e.name === 'live.jsonl') hits.push(join(dir, e.name));
    else if (e.isDirectory() && e.name !== '.git' && e.name !== 'worktree' && e.name !== 'node_modules') {
      await walk(join(dir, e.name), depth + 1, hits);
    }
  }
  return hits;
}

const runsRoot = process.env.SEAM_RUNS_ROOT;
const run = await activeRun(runsRoot);
const out = { run_dir: run?.dir ?? null, resolved: null, on_disk: [] };
if (run?.dir) {
  out.resolved = await liveStreamPath(run.dir);
  out.on_disk = await walk(run.dir, 0, []);
}
process.stdout.write(JSON.stringify(out));
"""


def check_live_stream(c: Check) -> None:
    """The board's reader must find the stream the harness actually writes."""
    dash = REPO / "dashboard"
    node = shutil.which("node")
    if node is None:
        c.add(
            "board live stream",
            True,
            "node not on PATH — reader seam unverified",
            blocking=False,
        )
        return
    if not (dash / "sources" / "_runtime.mjs").is_file():
        c.add(
            "board live stream",
            True,
            "dashboard sources absent — nothing to verify",
            blocking=False,
        )
        return

    proc = subprocess.run(
        [node, "--input-type=module", "-e", STREAM_SEAM_JS],
        capture_output=True,
        text=True,
        check=False,
        cwd=str(dash),
        timeout=60,
        env={**os.environ, "SEAM_RUNS_ROOT": str(REPO / "runs")},
    )
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout or "").strip().splitlines()
        c.add(
            "board live stream",
            False,
            "the dashboard's stream resolver FAILED TO RUN: "
            + (detail[-1][:160] if detail else f"exit {proc.returncode}"),
        )
        return
    try:
        res = json.loads(proc.stdout)
    except json.JSONDecodeError:
        c.add(
            "board live stream",
            False,
            f"resolver returned unparseable output: {proc.stdout[:120]!r}",
        )
        return

    run_dir = res.get("run_dir")
    resolved = res.get("resolved")
    on_disk = res.get("on_disk") or []

    if not run_dir:
        c.add(
            "board live stream",
            True,
            "no run on disk yet — reader seam unverified until a cell has written one",
            blocking=False,
        )
        return

    rel = Path(run_dir).name
    if not on_disk:
        # Pre-launch on a fresh tree. Nothing to disagree about YET.
        c.add(
            "board live stream",
            True,
            f"no live.jsonl under the active run ({rel}) — nothing written yet, seam unverified",
            blocking=False,
        )
        return

    if resolved is None:
        found = (
            Path(on_disk[0]).relative_to(Path(run_dir).parent.parent)
            if len(on_disk)
            else ""
        )
        c.add(
            "board live stream",
            False,
            f"BOARD IS BLIND: {len(on_disk)} live.jsonl on disk under the active run but the "
            f"dashboard resolver found NONE (e.g. .../{found}). The gate wall and the learning "
            "matrix will read 'no live.jsonl yet' for the WHOLE run. Fix "
            "dashboard/sources/_runtime.mjs::liveStreamPath — do NOT launch onto a blind board.",
        )
        return

    if resolved not in on_disk:
        c.add(
            "board live stream",
            False,
            f"resolver returned {resolved!r}, which is not among the {len(on_disk)} stream(s) "
            "actually on disk — reader and writer disagree about WHERE the stream lives.",
        )
        return

    extra = f" ({len(on_disk)} on disk, newest wins)" if len(on_disk) > 1 else ""
    c.add(
        "board live stream",
        True,
        f"reader resolves the harness's own stream{extra}: "
        f"{Path(resolved).relative_to(Path(run_dir))}",
    )


def check_disk(c: Check) -> None:
    usage = shutil.disk_usage(REPO)
    free_gb = usage.free / 1e9
    c.add(
        "disk free",
        free_gb > 10,
        f"{free_gb:.1f} GB free"
        + ("" if free_gb > 10 else " — LOW, a run can fill this"),
        blocking=False,
    )


